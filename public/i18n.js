export function translateMessage(locale, descriptor, fallback = "") {
  const normalized = normalizeLocale(locale) || "en";
  if (normalized === "zh-CN") return fallback || descriptor?.params?.text || "";
  if (!descriptor?.code) return translateFixedText(normalized, fallback);
  if (descriptor.code === "legacy.text") {
    return translateFixedText(normalized, descriptor.params?.text ?? fallback);
  }
  const template = semanticEnglish[descriptor.code];
  if (!template) return translateFixedText(normalized, fallback) || "Request failed";
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (_, name) =>
    String(descriptor.params?.[name] ?? `{${name}}`),
  );
}

