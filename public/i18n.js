const sourceText = new WeakMap();
const sourceAttributes = new WeakMap();

export function translateFixedText(locale, value) {
  if ((normalizeLocale(locale) || "en") === "zh-CN") return String(value);
  const text = String(value);
  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  const core = text.slice(leading.length, text.length - trailing.length || undefined);
  const exact = fixedEnglishText[core];
  if (exact) return `${leading}${exact}${trailing}`;
  let translated = core;
  for (const [pattern, replacement] of fixedEnglishPatterns) {
    translated = translated.replace(pattern, replacement);
  }
  return translated === core ? text : `${leading}${translated}${trailing}`;
}

export function localizeTree(root, locale) {
  const elementRoot = root.nodeType === Node.ELEMENT_NODE ? root : document.documentElement;
  const walker = document.createTreeWalker(elementRoot, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    if (node.parentElement?.closest("[data-i18n], [data-i18n-preserve], code, pre, script, style")) continue;
    if (!sourceText.has(node)) sourceText.set(node, node.nodeValue ?? "");
    const original = sourceText.get(node);
    node.nodeValue = normalizeLocale(locale) === "zh-CN"
      ? original
      : translateFixedText(locale, original);
  }
  const attributes = ["aria-label", "placeholder", "title", "data-label"];
  const elements = [
    ...(elementRoot.matches?.("*") ? [elementRoot] : []),
    ...(elementRoot.querySelectorAll?.("*") ?? []),
  ];
  for (const element of elements) {
    if (element.closest("[data-i18n], [data-i18n-preserve]")) continue;
    let originals = sourceAttributes.get(element);
    if (!originals) {
      originals = {};
      sourceAttributes.set(element, originals);
    }
    for (const attribute of attributes) {
      if (!element.hasAttribute(attribute)) continue;
      originals[attribute] ??= element.getAttribute(attribute);
      element.setAttribute(
        attribute,
        normalizeLocale(locale) === "zh-CN"
          ? originals[attribute]
          : translateFixedText(locale, originals[attribute]),
      );
    }
  }
}

export function observeTranslations(root, locale) {
  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      for (const node of mutation.addedNodes) {
        if (node.nodeType === Node.ELEMENT_NODE) localizeTree(node, locale());
        if (node.nodeType === Node.TEXT_NODE && node.parentElement) {
          localizeTree(node.parentElement, locale());
        }
      }
    }
  });
  observer.observe(root, { childList: true, subtree: true });
  return () => observer.disconnect();
}

export function normalizeLocale(value) {
  if (typeof value !== "string") return null;
  const normalized = value.trim().toLowerCase();
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  if (
    normalized === "zh" ||
    normalized === "zh-cn" ||
    normalized === "zh-hans" ||
    normalized.startsWith("zh-hans-")
  ) {
    return "zh-CN";
  }
  return null;
}

export function resolveLocale({ saved, browserLanguages = [] } = {}) {
  const savedLocale = normalizeLocale(saved);
  if (savedLocale) return savedLocale;
  for (const language of browserLanguages) {
    const locale = normalizeLocale(language);
    if (locale) return locale;
  }
  return "en";
}

export function translate(locale, key, params = {}) {
  const template = catalogs[normalizeLocale(locale) || "en"]?.[key] ?? catalogs.en[key] ?? key;
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (_, name) =>
    String(params[name] ?? `{${name}}`),
  );
}

export function catalogParameterNames(value) {
  return [...String(value).matchAll(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g)]
    .map((match) => match[1])
    .sort();
}

export function applyStaticTranslations(root, locale) {
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(locale, element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", translate(locale, element.dataset.i18nAriaLabel));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", translate(locale, element.dataset.i18nPlaceholder));
  });
  document.documentElement.lang = normalizeLocale(locale) || "en";
  document.title = translate(locale, "app.title");
}
